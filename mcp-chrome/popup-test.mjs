import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
import assert from 'node:assert';
import path from 'node:path'; import os from 'node:os'; import fs from 'node:fs';
const ext = path.resolve('extension');
const ctx = await chromium.launchPersistentContext(fs.mkdtempSync(path.join(os.tmpdir(), 'mcpx-')), { channel: 'chrome', headless: false, ignoreDefaultArgs: ['--disable-extensions'], args: ['--enable-unsafe-extension-debugging'] });
const cdp = await ctx.browser().newBrowserCDPSession();
const { id } = await cdp.send('Extensions.loadUnpacked', { path: ext });
const sw = ctx.serviceWorkers()[0] ?? (await ctx.waitForEvent('serviceworker'));
await sw.evaluate(() => chrome.storage.local.set({ ports: [9333] }));
const page = await ctx.newPage();
await page.goto(`chrome-extension://${id}/popup.html`);
await page.waitForFunction(() => document.getElementById('msg').textContent !== 'Checking…');
console.log('no server  :', await page.textContent('#msg'), '| copy button visible:', await page.isVisible('#copy'));
assert.equal(await page.textContent('#msg'), 'Not connected');
await page.screenshot({ path: '../qa/popup-off.png' });
const srv = spawn('node', ['ext-server.mjs'], { env: { ...process.env, MCP_CHROME_PORT: '9333' }, stdio: ['pipe', 'ignore', 'ignore'] });
await new Promise((r) => setTimeout(r, 1500));
await page.click('#retry');
await page.waitForFunction(() => /Connected/.test(document.getElementById('msg').textContent), null, { timeout: 8000 });
console.log('with server:', await page.textContent('#msg'), '| copy button visible:', await page.isVisible('#copy'));
await page.screenshot({ path: '../qa/popup-on.png' });
srv.kill(); await ctx.close(); process.exit(0);
